// @ts-check
// One-off (run by hand, not part of any build): renders the horizontal CSPS lockup for the auth emails (D-30) to
// src/Csps.Infrastructure/Email/Assets/csps-logo.png, a 360 px wide PNG (2x of the 180 px the emails show), and writes
// the same bytes as base64 into src/Csps.Infrastructure/Email/EmailLogoPng.cs, which is what the build compiles in.
//   1. Start the dev server:  npm --prefix web run dev   (http://localhost:5180)
//   2. Run:                   node web/scripts/render-email-logo.mjs [--base-url http://localhost:5180]
//   Only rewrite the C# file from the committed PNG:  node web/scripts/render-email-logo.mjs --encode-only
// It copies the Logo of the showcase case "logo-lg" onto a #fff6f0 (the email card colour) page, scales it to 180 px
// and takes a clip at device scale factor 2. Commit both files.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const CARD = '#fff6f0';
const EMAIL_WIDTH = 180;
const OUTPUT = fileURLToPath(new URL('../../src/Csps.Infrastructure/Email/Assets/csps-logo.png', import.meta.url));
const CSHARP = fileURLToPath(new URL('../../src/Csps.Infrastructure/Email/EmailLogoPng.cs', import.meta.url));
const LINE = 120;

/** Writes the PNG's bytes into the C# file the build compiles in. */
function writeCSharp() {
  const base64 = readFileSync(OUTPUT).toString('base64');
  const lines = base64.match(new RegExp(`.{1,${String(LINE)}}`, 'g')) ?? [];
  const source = [
    '// <auto-generated>',
    '// Written by web/scripts/render-email-logo.mjs from Assets/csps-logo.png. Do not edit by hand.',
    '// </auto-generated>',
    '',
    'namespace Csps.Infrastructure.Email;',
    '',
    '// The 2x PNG of the horizontal CSPS lockup (D-30), compiled in so it can never be missing at run time.',
    'internal static class EmailLogoPng',
    '{',
    '    internal const string Base64 = """',
    ...lines.map((line) => `        ${line}`),
    '        """;',
    '}',
    '',
  ].join('\n');
  writeFileSync(CSHARP, source);
  process.stdout.write(`render-email-logo: wrote ${CSHARP}\n`);
}

async function render() {
  const { chromium } = await import('@playwright/test');
  const flag = process.argv.indexOf('--base-url');
  const baseUrl = (flag > -1 ? process.argv[flag + 1] : undefined) ?? 'http://localhost:5180';

  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({
      deviceScaleFactor: 2,
      viewport: { width: 1200, height: 900 },
      colorScheme: 'light',
    });
    const page = await context.newPage();
    await page.goto(`${baseUrl}/dev/components`, { waitUntil: 'networkidle' });
    const source = page.locator('[data-case="logo-lg"] [role="img"]').first();
    await source.waitFor();
    await page.evaluate('document.fonts.ready');

    // Copy the lockup to the top left of a clean card-coloured layer, scaled so it is exactly 180 px wide. The page script
    // is a string, as in owner-review.mjs, because this file is linted as Node code with no DOM types.
    await page.evaluate(`(() => {
      const logo = document.querySelector('[data-case="logo-lg"] [role="img"]');
      if (logo === null) {
        throw new Error('No logo-lg lockup on the showcase.');
      }
      const layer = document.createElement('div');
      layer.setAttribute('style', 'position:fixed;inset:0;z-index:2147483647;background:${CARD};');
      const copy = logo.cloneNode(true);
      copy.id = 'email-logo-copy';
      layer.append(copy);
      document.body.append(layer);
      copy.style.zoom = String(${String(EMAIL_WIDTH)} / copy.getBoundingClientRect().width);
    })()`);

    const box = await page.locator('#email-logo-copy').boundingBox();
    if (box === null) {
      throw new Error('The copied lockup has no box.');
    }
    mkdirSync(path.dirname(OUTPUT), { recursive: true });
    await page.screenshot({
      path: OUTPUT,
      clip: { x: Math.floor(box.x), y: Math.floor(box.y), width: EMAIL_WIDTH, height: Math.ceil(box.height) },
    });
    process.stdout.write(`render-email-logo: wrote ${OUTPUT}\n`);
  } finally {
    await browser.close();
  }
}

if (!process.argv.includes('--encode-only')) {
  await render();
}
writeCSharp();
