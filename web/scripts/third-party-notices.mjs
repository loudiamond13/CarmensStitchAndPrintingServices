// @ts-check
// Writes web/THIRD-PARTY-NOTICES.txt from the production npm tree of web/ (the packages that ship to the browser;
// D-10 credit). `--check` regenerates it in memory and exits 1 when the committed file differs.
//   node web/scripts/third-party-notices.mjs           (rewrite the file)
//   node web/scripts/third-party-notices.mjs --check   (fail when it is out of date)
// The file has no timestamp, so it changes only when the package graph changes. Reads only node_modules.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { formatNotices } from './license-policy.mjs';
import { readTree } from './npm-tree.mjs';

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const noticesPath = resolve(webRoot, 'THIRD-PARTY-NOTICES.txt');

const HEADER = [
  'THIRD-PARTY NOTICES: CSPS web app (web/)',
  '',
  'The open-source packages that ship to the browser as part of the CSPS web app, with their licenses.',
  'Every one is free to use. Each line: package@version | license (SPDX id) | source repository.',
  "The full license text of each package is in its LICENSE file and in the package's source repository.",
  '',
  'Generated by web/scripts/third-party-notices.mjs from the production npm tree of web/. Do not edit by hand:',
  'run `node web/scripts/third-party-notices.mjs` after any change to web/package.json and commit the result.',
  '`node web/scripts/third-party-notices.mjs --check` fails when this file is out of date.',
  "Each production build also writes Vite's own license list (build.license) to .vite/license.md in the build output;",
  'it covers only the code that is actually bundled. The .NET packages are listed in THIRD-PARTY-NOTICES.md at the',
  'repository root.',
  '',
];

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });

const lines = formatNotices(await readTree(webRoot, true));
const expected = [...HEADER, ...lines, ''].join('\n');

if (!values.check) {
  writeFileSync(noticesPath, expected);
  console.log(`Wrote ${noticesPath} (${String(lines.length)} packages).`);
} else {
  const committed = existsSync(noticesPath) ? readFileSync(noticesPath, 'utf8').replaceAll('\r\n', '\n') : '';
  if (committed === expected) {
    console.log(`THIRD-PARTY-NOTICES.txt is up to date (${String(lines.length)} packages).`);
  } else {
    const before = new Set(committed.split('\n'));
    const after = new Set(expected.split('\n'));
    const added = [...after].filter((line) => !before.has(line));
    const removed = [...before].filter((line) => !after.has(line));
    console.error('web/THIRD-PARTY-NOTICES.txt is out of date with the production npm tree.');
    for (const line of added) {
      console.error(`  + ${line}`);
    }
    for (const line of removed) {
      console.error(`  - ${line}`);
    }
    if (committed.length === 0) {
      console.error('  (the file is missing)');
    }
    console.error('Run `node web/scripts/third-party-notices.mjs` and commit the result.');
    process.exitCode = 1;
  }
}
